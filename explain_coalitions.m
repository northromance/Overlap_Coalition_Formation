%% 解释联盟数量与智能体数量的关系

fprintf('========================================\n');
fprintf('  联盟数量 vs 智能体数量 解释\n');
fprintf('========================================\n\n');

% 模拟场景参数
N = 6;   % 智能体数量
M = 10;  % 任务数量

fprintf('场景设置:\n');
fprintf('  - 智能体数量: %d\n', N);
fprintf('  - 任务数量: %d\n', M);
fprintf('\n');

fprintf('重叠联盟模型的核心概念:\n');
fprintf('  1. 每个任务可以形成一个联盟\n');
fprintf('  2. 每个联盟由若干智能体组成\n');
fprintf('  3. 同一个智能体可以同时参与多个联盟\n');
fprintf('  4. 联盟数量 = 被分配的任务数量\n');
fprintf('\n');

fprintf('示例: 贪婪算法形成9个联盟\n');
fprintf('  含义: 10个任务中，有9个任务得到了智能体资源分配\n');
fprintf('  说明: 1个任务没有被分配（可能资源不足）\n');
fprintf('\n');

fprintf('智能体参与情况示例:\n');
fprintf('  智能体1 可能参与了 任务1, 任务3, 任务5 (3个联盟)\n');
fprintf('  智能体2 可能参与了 任务2, 任务4       (2个联盟)\n');
fprintf('  智能体3 可能参与了 任务1, 任务2       (2个联盟)\n');
fprintf('  ...\n');
fprintf('  总计形成9个联盟 (对应9个有智能体的任务)\n');
fprintf('\n');

fprintf('对比:\n');
fprintf('  互斥联盟: 每个智能体只能属于1个联盟\n');
fprintf('           → 联盟数量 ≤ 智能体数量\n');
fprintf('  重叠联盟: 每个智能体可以属于多个联盟\n');
fprintf('           → 联盟数量 ≤ 任务数量\n');
fprintf('\n');

fprintf('========================================\n');
